#!/usr/bin/env node
// Embeds the widget code in views/*.js into main.js, so the plugin carries its own widgets
// and a plugin update is all it takes to update them.
//
//   node scripts/bundle-views.mjs                   rewrite the generated block at the end of main.js
//   node scripts/bundle-views.mjs --check           exit 1 when main.js is out of date (used by the release workflow)
//   node scripts/bundle-views.mjs --deploy <vault>  bundle, then copy main.js, manifest.json and styles.css
//                                                   into <vault>/.obsidian/plugins/ex3c-agenda/
//   node scripts/bundle-views.mjs --stubs <vault>   turn <vault>/Meta/views/<name>.js into stubs that run the
//                                                   built-in code; a file that differs from views/<name>.js is
//                                                   left alone and listed, because it holds someone's own changes
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const START = "// ---------- built-in widget code: generated by scripts/bundle-views.mjs from views/*.js; edit those files, not this block ----------";
const END = "// ---------- end of built-in widget code ----------";
const STUB_MARK = "ex3c-builtin-widget";

const viewDir = path.join(root, "views");
const names = fs.readdirSync(viewDir).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();
const source = (name) => fs.readFileSync(path.join(viewDir, `${name}.js`), "utf8");

function bundled(main) {
  const block = `${START}\nconst BUILTIN_VIEWS = Object.freeze({\n${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(source(n))},`).join("\n")}\n});\n${END}\n`;
  const i = main.indexOf(START);
  if (i === -1) return `${main.replace(/\n*$/, "\n\n")}${block}`;
  const j = main.indexOf(END, i);
  if (j === -1) throw new Error("main.js has the start marker of the widget block but not its end");
  return main.slice(0, i) + block + main.slice(j + END.length).replace(/^\n/, "");
}

// The same text the plugin writes with "Reset widget to built-in" (widgetStub in main.js).
function stub(name) {
  if (name === "setup-checks") {
    return `// ${STUB_MARK}\n// The setup checks are built into the EX3C AgendA plugin and update with it (the Setup note and the Home banner use them).\n// To change them, run the command "EX3C AgendA: Edit widget code" and pick setup-checks; your copy then replaces this file.\n`;
  }
  return `// ${STUB_MARK}\n// The "${name}" widget is built into the EX3C AgendA plugin and updates with it. Notes run it through this file.\n// To change its code, run the command "EX3C AgendA: Edit widget code" and pick ${name}; your copy then replaces this file.\nconst ex3c = dv.app.plugins.plugins["ex3c-agenda"];\nif (ex3c?.runWidget) await ex3c.runWidget(${JSON.stringify(name)}, dv, input, true);\nelse dv.paragraph("Turn on the EX3C AgendA plugin to show this widget.");\n`;
}

const args = process.argv.slice(2);
const mainPath = path.join(root, "main.js");
const current = fs.readFileSync(mainPath, "utf8");
const next = bundled(current);

if (args[0] === "--check") {
  if (next !== current) { console.error("main.js is out of date: run node scripts/bundle-views.mjs"); process.exit(1); }
  console.log(`main.js carries the current code of ${names.length} widgets`);
  process.exit(0);
}

if (args[0] === "--stubs") {
  const vault = args[1];
  if (!vault) throw new Error("--stubs needs the vault folder");
  const dir = path.join(vault, "Meta", "views");
  const kept = [];
  let written = 0;
  fs.mkdirSync(dir, { recursive: true });
  for (const name of names) {
    const file = path.join(dir, `${name}.js`);
    const text = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (text !== null && text !== source(name) && !text.includes(STUB_MARK)) { kept.push(name); continue; }
    if (text !== stub(name)) { fs.writeFileSync(file, stub(name)); written++; }
  }
  console.log(`${written} stub${written === 1 ? "" : "s"} written in ${dir}`);
  if (kept.length) console.log(`Left alone because they differ from views/: ${kept.join(", ")}`);
  process.exit(0);
}

if (next !== current) fs.writeFileSync(mainPath, next);
console.log(`main.js carries ${names.length} widgets${next === current ? " (no change)" : ""}`);

if (args[0] === "--deploy") {
  const vault = args[1];
  if (!vault) throw new Error("--deploy needs the vault folder");
  const target = path.join(vault, ".obsidian", "plugins", "ex3c-agenda");
  if (!fs.existsSync(target)) throw new Error(`${target} does not exist`);
  for (const f of ["main.js", "manifest.json", "styles.css"]) fs.copyFileSync(path.join(root, f), path.join(target, f));
  console.log(`Copied main.js, manifest.json and styles.css to ${target}; reload the plugin in Obsidian to use them`);
}
